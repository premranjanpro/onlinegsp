function initHomeCourseTabs() {

    renderTabFromJson(1);

    // attach to nav links (.nav.nav-tabs a[data-bs-toggle="tab"])
    const navLinks = document.querySelectorAll('.nav.nav-tabs a[data-bs-toggle="tab"]');
    if (!navLinks || navLinks.length === 0) return;

    navLinks.forEach((a, idx) => {
        // idx 0 => tab1, idx1 => tab2 ...
        const tabId = idx + 1;

    // If Bootstrap's shown.bs.tab event exists, use it (fires after bootstrap activates pane)
    a.addEventListener('shown.bs.tab', function (e) {
        try { renderTabFromJson(tabId); } catch (err) { console.warn('renderTabFromJson error', err); }
    });

    // Fallback: if Bootstrap event not available (or for direct clicks), also handle click
    a.addEventListener('click', function (ev) {
        // small timeout to allow bootstrap to toggle classes if present
        setTimeout(() => {
            try { renderTabFromJson(tabId); } catch (err) { console.warn('renderTabFromJson error', err); }
}, 50);
});
});
}

